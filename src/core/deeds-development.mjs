// The dungeon's elemental paths remain separately navigable in the Forge.
const schools = { flame: "elements", frost: "elements", storm: "elements", mind: "mentalism", calling: "invocation", radiance: "wards" };
export const deedsHero = draft => draft?.forge?.version === 2;
export function disciplinePrice(draft, node) {
  if (node?.kind !== "origin" || !deedsHero(draft)) return node?.cost ?? 0;
  return DEEDS_CLASSES[draft.classId]?.prices[schools[node.discipline] ?? node.discipline] ?? node.cost;
}
export function deedsDP(draft, level = draft.progression?.level ?? 1) {
  const a = draft.attributes ?? {};
  const adaptable = draft.traitIds?.includes("trait-human-far-walker") || draft.borrowedTraitId === "trait-human-far-walker";
  const growth = (level - 1) * 6 + level * (level + 1) / 2 - 1;
  return 10 + (a.guile ?? 0) + (a.knowledge ?? 0) + (a.reason ?? 0) + growth + (adaptable ? level : 0);
}
export function deedsVitals(draft, fixedHP = 0, bonusSP = 0) {
  const a = DEEDS_ANCESTRIES[draft.ancestryId];
  const c = DEEDS_CLASSES[draft.classId];
  const level = draft.progression?.level ?? 1;
  return {
    maximumHp: 10 + level * ((a?.hp ?? 0) + (c?.hp ?? 0)) + (draft.attributes?.fortitude ?? 0) + fixedHP,
    maximumSp: 2 * level + (a?.sp ?? 0) + 2 * Math.max(0, draft.attributes?.[c?.casting] ?? 0) + bonusSP,
    gritGranted: 1 + Number(level >= 3) + Number(level >= 7),
  };
}
