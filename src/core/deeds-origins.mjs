const atlas = {
  elements: ["flame", "frost", "storm"],
  mentalism: ["mind"],
  invocation: ["calling"],
  wards: ["radiance"],
};
export function atlasStudies(fields) {
  return fields.flatMap((field) =>
    (atlas[field] ?? [field]).map((id) => "discipline-" + id),
  );
}
export function fieldOf(node) {
  const branch = node.split(":")[0];
  return (
    Object.keys(atlas).find((field) => atlas[field].includes(branch)) ?? branch
  );
}

